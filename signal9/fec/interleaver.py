"""Interleavers and de-interleavers for all four families the problem statement names.

The problem statement requires de-interleaving of **block, convolutional,
diagonal (helical) and pseudo-random** interleavers.  This module provides the
forward and inverse transform for each; the blind parameter estimators that
decide *which* family and *which* parameters a captured stream used live in
:mod:`signal9.label.interleaver_detect`.

Every transform here is index-only, so it applies unchanged to hard bits, to
soft LLRs and to byte-wide symbols -- CCSDS-style concatenated chains interleave
RS symbols rather than bits.  That is why these functions accept and return
arrays of any dtype instead of forcing uint8.

Families
--------
Block (row-column)
    Write row-by-row into an R x C matrix, read column-by-column.
    Satisfies KAT-INTLV-1: ``block_deinterleave(block_interleave(x, R, C), R, C) == x``.

Convolutional (Forney / Ramsey II)
    ``B`` branches with delays ``0, M, 2M, ... (B-1)M`` symbol periods, visited
    in turn by a commutator.  Unlike a block interleaver it has no frame
    boundary and so needs no block synchronisation, which is why it dominates
    broadcast links (DVB uses B=12, M=17).  End-to-end delay is a constant
    ``(B-1)*M*B`` samples, returned by :func:`convolutional_interleaver_delay`.

Helical / diagonal
    Write row-by-row into an R x C matrix, read along diagonals whose start
    column advances by ``slope`` per row.  This spreads a burst across both rows
    and columns, which a plain block interleaver does not.

Pseudo-random
    An explicit permutation: either drawn from a seeded PRNG or generated by a
    standard algebraic rule (3GPP LTE quadratic permutation polynomial).  These
    are not blindly recoverable at useful lengths, so the detector treats them
    semi-blindly, against a library of known permutations.

Spec reference: KAT-INTLV-1, PS26147 requirement (iii).
"""
from __future__ import annotations
import numpy as np


def block_interleave(data: np.ndarray, R: int, C: int) -> np.ndarray:
    """Interleave data using an R x C block matrix (write rows, read columns).

    Parameters
    ----------
    data : 1D array of length R * C (or integer multiple)
    R : int (number of rows)
    C : int (number of columns)

    Returns
    -------
    1D array of same length and dtype
    """
    data = np.asarray(data)
    block_len = R * C
    n_blocks = len(data) // block_len
    if n_blocks == 0:
        return data.copy()

    # Process all full blocks
    usable_len = n_blocks * block_len
    blocks = data[:usable_len].reshape(n_blocks, R, C)
    interleaved_blocks = np.transpose(blocks, (0, 2, 1)).reshape(usable_len)

    if len(data) > usable_len:
        # Append remaining elements unchanged
        return np.concatenate([interleaved_blocks, data[usable_len:]])
    return interleaved_blocks


def block_deinterleave(data: np.ndarray, R: int, C: int) -> np.ndarray:
    """Deinterleave data using an R x C block matrix (write columns, read rows).

    Parameters
    ----------
    data : 1D array of length R * C (or integer multiple)
    R : int (number of rows)
    C : int (number of columns)

    Returns
    -------
    1D array of same length and dtype
    """
    data = np.asarray(data)
    block_len = R * C
    n_blocks = len(data) // block_len
    if n_blocks == 0:
        return data.copy()

    usable_len = n_blocks * block_len
    blocks = data[:usable_len].reshape(n_blocks, C, R)
    deinterleaved_blocks = np.transpose(blocks, (0, 2, 1)).reshape(usable_len)

    if len(data) > usable_len:
        return np.concatenate([deinterleaved_blocks, data[usable_len:]])
    return deinterleaved_blocks


# ─────────────────────────────────────────────────────────────────────────────
# Convolutional (Forney) interleaver
# ─────────────────────────────────────────────────────────────────────────────

def convolutional_interleaver_delay(branches: int, delay: int) -> int:
    """End-to-end latency of an interleave/deinterleave pair, in samples.

    Every symbol traverses one interleaver branch (``j*delay`` commutator visits)
    and the matching deinterleaver branch (``(B-1-j)*delay`` visits), so the sum
    is ``(B-1)*delay`` visits for every ``j`` -- a constant, which is the whole
    point of the Forney structure.  Successive visits of one branch are ``B``
    samples apart, hence ``(B-1)*delay*B`` samples overall.
    """
    return max(0, (int(branches) - 1) * int(delay) * int(branches))


def _forney_shift(data: np.ndarray, branches: int, delay: int, invert: bool) -> np.ndarray:
    """Shared kernel for the Forney interleaver and its inverse.

    Branch ``j`` is visited at global indices ``j, j+B, j+2B, ...``.  Giving that
    branch a delay of ``d_j`` visits means the value emitted on its k-th visit is
    the value that entered on visit ``k - d_j``; earlier visits emit the fill
    value (zero).  The interleaver uses ``d_j = j*M`` and the deinterleaver the
    complementary ``d_j = (B-1-j)*M``, which is what makes the total delay equal
    for every branch.
    """
    data = np.asarray(data)
    B = int(branches)
    M = int(delay)
    if B <= 1 or M <= 0 or data.size == 0:
        return data.copy()

    n = len(data)
    out = np.zeros(n, dtype=data.dtype)
    idx = np.arange(n)
    j = idx % B                       # branch serving each output position
    k = idx // B                      # which visit of that branch
    d = (B - 1 - j) * M if invert else j * M
    src_visit = k - d
    valid = src_visit >= 0
    src = j + src_visit * B
    valid &= src < n
    out[valid] = data[src[valid]]
    return out


def convolutional_interleave(data: np.ndarray, branches: int = 12, delay: int = 17) -> np.ndarray:
    """Forney convolutional interleaver with ``branches`` branches, step ``delay``.

    Defaults are the DVB-S/DVB-T values (B=12, M=17).  The output is the same
    length as the input; symbols pushed past the end are dropped, so append
    ``convolutional_interleaver_delay(branches, delay)`` fill samples before
    interleaving when the tail matters.
    """
    return _forney_shift(data, branches, delay, invert=False)


def convolutional_deinterleave(data: np.ndarray, branches: int = 12, delay: int = 17) -> np.ndarray:
    """Inverse of :func:`convolutional_interleave`.

    ``convolutional_deinterleave(convolutional_interleave(x, B, M), B, M)``
    reproduces ``x`` delayed by ``convolutional_interleaver_delay(B, M)``
    samples; use :func:`strip_convolutional_delay` to realign.
    """
    return _forney_shift(data, branches, delay, invert=True)


def strip_convolutional_delay(data: np.ndarray, branches: int, delay: int) -> np.ndarray:
    """Drop the constant pipeline delay left by a convolutional deinterleave."""
    d = convolutional_interleaver_delay(branches, delay)
    data = np.asarray(data)
    return data[d:] if d < len(data) else data[:0]


# ─────────────────────────────────────────────────────────────────────────────
# Helical / diagonal interleaver
# ─────────────────────────────────────────────────────────────────────────────

def _helical_read_order(rows: int, cols: int, slope: int) -> np.ndarray:
    """Flat source indices for a helical read of a row-filled ``rows x cols`` block.

    Output position ``c*rows + r`` takes the element at matrix cell
    ``(r, (c + slope*r) mod cols)``: as the row index advances, the read head
    walks ``slope`` columns sideways, tracing a diagonal that wraps around.
    With ``slope == 0`` this degenerates to a plain column read -- the block
    interleaver -- which is why the detector scores ``slope >= 1`` as a family of
    its own.
    """
    r = np.arange(rows).reshape(rows, 1)
    c = np.arange(cols).reshape(1, cols)
    src_col = (c + slope * r) % cols
    # Transpose so the flat read order runs down the diagonals, not across rows.
    return (r * cols + src_col).T.reshape(-1)


def helical_interleave(data: np.ndarray, rows: int, cols: int, slope: int = 1) -> np.ndarray:
    """Diagonal (helical scan) interleaver over ``rows x cols`` blocks."""
    data = np.asarray(data)
    block = int(rows) * int(cols)
    if block <= 0 or len(data) < block:
        return data.copy()
    order = _helical_read_order(int(rows), int(cols), int(slope))
    n_blocks = len(data) // block
    usable = n_blocks * block
    out = data[:usable].reshape(n_blocks, block)[:, order].reshape(-1)
    if usable == len(data):
        return out
    return np.concatenate([out, data[usable:]])


def helical_deinterleave(data: np.ndarray, rows: int, cols: int, slope: int = 1) -> np.ndarray:
    """Inverse of :func:`helical_interleave`."""
    data = np.asarray(data)
    block = int(rows) * int(cols)
    if block <= 0 or len(data) < block:
        return data.copy()
    order = _helical_read_order(int(rows), int(cols), int(slope))
    inv = np.empty_like(order)
    inv[order] = np.arange(block)
    n_blocks = len(data) // block
    usable = n_blocks * block
    out = data[:usable].reshape(n_blocks, block)[:, inv].reshape(-1)
    if usable == len(data):
        return out
    return np.concatenate([out, data[usable:]])


# ─────────────────────────────────────────────────────────────────────────────
# Pseudo-random interleaver
# ─────────────────────────────────────────────────────────────────────────────

def prng_permutation(size: int, seed: int) -> np.ndarray:
    """Reproducible pseudo-random permutation of ``range(size)``.

    Uses NumPy's PCG64 through an explicit seed, so the same ``(size, seed)``
    pair yields the same permutation on every platform.
    """
    return np.random.default_rng(int(seed)).permutation(int(size))


def qpp_permutation(size: int, f1: int, f2: int) -> np.ndarray:
    """3GPP LTE quadratic permutation polynomial ``pi(i) = (f1*i + f2*i^2) mod K``.

    This is the LTE turbo interleaver (36.212 Table 5.1.3-3).  It is a bijection
    only for admissible ``(K, f1, f2)`` triples, so the result is validated and a
    ``ValueError`` is raised otherwise: a non-bijective "permutation" would drop
    and duplicate symbols silently.
    """
    K = int(size)
    i = np.arange(K, dtype=np.int64)
    perm = (int(f1) * i + int(f2) * i * i) % K
    if np.unique(perm).size != K:
        raise ValueError(f"(K={K}, f1={f1}, f2={f2}) is not a valid QPP permutation")
    return perm


def permutation_interleave(data: np.ndarray, perm: np.ndarray) -> np.ndarray:
    """Apply an explicit permutation blockwise: ``out[i] = data[perm[i]]``."""
    data = np.asarray(data)
    perm = np.asarray(perm, dtype=np.int64)
    block = len(perm)
    if block <= 0 or len(data) < block:
        return data.copy()
    n_blocks = len(data) // block
    usable = n_blocks * block
    out = data[:usable].reshape(n_blocks, block)[:, perm].reshape(-1)
    if usable == len(data):
        return out
    return np.concatenate([out, data[usable:]])


def permutation_deinterleave(data: np.ndarray, perm: np.ndarray) -> np.ndarray:
    """Inverse of :func:`permutation_interleave`."""
    perm = np.asarray(perm, dtype=np.int64)
    inv = np.empty_like(perm)
    inv[perm] = np.arange(len(perm), dtype=np.int64)
    return permutation_interleave(data, inv)
